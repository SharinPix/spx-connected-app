import { SfCommand, Flags } from '@salesforce/sf-plugins-core';
import { Messages, AuthInfo, Connection, Org } from '@salesforce/core';

Messages.importMessagesDirectory(__dirname);
const messages = Messages.loadMessages('@sharinpix/spx-connected-app', 'ext.create');

export type CreateResult = { fullName: string; success: boolean }

export type Valuable<T> = { [K in keyof T as T[K] extends null | undefined ? never : K]: T[K] };

function getValuable<
  // eslint-disable-next-line @typescript-eslint/ban-types
  T extends {},
  V = Valuable<T>,
>(obj: T): V {
  return Object.fromEntries(
    Object.entries(obj).filter(
      ([, v]) =>
        !(
          (typeof v === 'string' && !v.length) ||
          v === null ||
          typeof v === 'undefined'
        ),
    ),
  ) as V;
}

/** Creates an ExternalClientApplication via the Metadata API. */
export default class ExtCreate extends SfCommand<CreateResult> {
  public static readonly summary = messages.getMessage('summary');
  public static readonly description = messages.getMessage('description');
  public static readonly examples = messages.getMessages('examples');

  public static readonly flags = {
    name: Flags.string({
      summary: messages.getMessage('flags.name.summary'),
      char: 'n',
      required: false,
    }),
    username: Flags.string({
      summary: messages.getMessage('flags.username.summary'),
      char: 'u',
      required: true,
    }),
    'oauth-callback-url': Flags.string({
      summary: messages.getMessage('flags.oauth-callback-url.summary'),
      char: 'c',
    }),
    email: Flags.string({
      summary: messages.getMessage('flags.email.summary'),
      char: 'e',
    }),
    scopes: Flags.string({
      summary: messages.getMessage('flags.scopes.summary'),
      char: 's',
    }),
    namespace: Flags.string({
      summary: messages.getMessage('flags.namespace.summary'),
      char: 'p',
    }),
    'distribution-state': Flags.custom<'Local' | 'Packageable'>({
      summary: messages.getMessage('flags.distribution-state.summary'),
      options: ['Local', 'Packageable'],
      default: 'Local',
    })(),
    'is-protected': Flags.boolean({
      summary: messages.getMessage('flags.is-protected.summary'),
      default: false,
    }),
  };

  public async run(): Promise<CreateResult> {
    const { flags } = await this.parse(ExtCreate);

    const username = flags.username;
    const fullName = flags.name;
    const label = fullName ?? 'External Client App';
    const contactEmail = flags.email;
    const callbackUrl = flags['oauth-callback-url'] ?? 'sfdx://success';
    const description = 'Generated by SharinPix';
    const scopes = flags.scopes?.split(',').filter(Boolean) ?? [];
    const namespace = flags.namespace;
    const distributionState = flags['distribution-state'];
    const isProtected = flags['is-protected'];

    const oauthConfig: Record<string, unknown> = { callbackUrl };
    if (scopes.length > 0) {
      oauthConfig.scopes = scopes;
    }

    let metadata: Record<string, unknown> = {
      contactEmail,
      description,
      distributionState,
      fullName: fullName ?? label,
      isProtected,
      label,
      oauthConfig,
    };

    metadata = getValuable(metadata);

    const org: Org = await Org.create({ aliasOrUsername: username });
    const authInfo = await AuthInfo.create({ username: org.getUsername() });
    const connection = await Connection.create({ authInfo });
    const results = await connection.metadata.create('ExternalClientApplication', metadata);

    if (results.success) {
      let appName = results.fullName;
      if (namespace) {
        appName = `${namespace}__${appName}`;
      }
      return (await connection.metadata.read(
        'ExternalClientApplication',
        appName,
      )) as unknown as CreateResult;
    }

    return results;
  }
}
