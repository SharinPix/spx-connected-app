import { SfCommand, Flags } from '@salesforce/sf-plugins-core';
import { Messages } from '@salesforce/core';
import { SaveResult } from '@jsforce/jsforce-node';

Messages.importMessagesDirectory(__dirname);
const messages = Messages.loadMessages('@sharinpix/spx-connected-app', 'ext.create');

export type CreateResult = { fullName: string; success: boolean; errors?: string[] };

/**
 * Removes empty strings, nulls, or undefined values to prevent API validation errors.
 */
function getValuable<T extends object>(obj: T): Partial<T> {
  return Object.fromEntries(
    Object.entries(obj).filter(
      ([, v]) => !(v === null || v === undefined || (typeof v === 'string' && v.length === 0))
    )
  ) as Partial<T>;
}

export default class ExtCreate extends SfCommand<CreateResult> {
  public static readonly summary = messages.getMessage('summary');

  public static readonly flags = {
    name: Flags.string({
      summary: messages.getMessage('flags.name.summary'),
      char: 'n',
      required: true,
    }),
    'target-org': Flags.requiredOrg({
      summary: messages.getMessage('flags.username.summary'),
      char: 'o',
    }),
    'oauth-callback-url': Flags.string({
      summary: messages.getMessage('flags.oauth-callback-url.summary'),
      char: 'c',
      required: true,
    }),
    email: Flags.string({
      summary: messages.getMessage('flags.email.summary'),
      char: 'e',
    }),
    scopes: Flags.string({
      summary: messages.getMessage('flags.scopes.summary'),
      char: 's',
      default: 'api',
    }),
    'distribution-state': Flags.custom<'Local' | 'Packageable'>({
      summary: messages.getMessage('flags.distribution-state.summary'),
      options: ['Local', 'Packageable'],
      default: 'Local',
    })(),
    'is-protected': Flags.boolean({
      summary: messages.getMessage('flags.is-protected.summary'),
      default: false,
    }),
  };

  public async run(): Promise<CreateResult> {
    const { flags } = await this.parse(ExtCreate);
    const connection = flags['target-org'].getConnection();
    const fullName = flags.name;
    const scopes = flags.scopes?.split(',').map((s) => s.trim()).filter(Boolean) ?? [];

    this.spinner.start(`Creating External Client App: ${fullName}`);

    try {
      // STEP 1: Create the Shell (ExternalClientApplication)
      const ecaMetadata = getValuable({
        fullName,
        label: fullName,
        contactEmail: flags.email,
        description: 'Created via SharinPix CLI',
        distributionState: flags['distribution-state'],
        isProtected: flags['is-protected'],
      });

      const ecaResult = (await connection.metadata.create('ExternalClientApplication', ecaMetadata)) as SaveResult;
      if (!ecaResult.success) {
        throw new Error(`ECA Shell Error: ${ecaResult.errors?.[0]?.message}`);
      }

      // STEP 2: Create the OAuth Settings (ExternalClientOauthSettings)
      // The API name for the settings file must be [Name]OauthSettings
      const oauthMetadata = {
        fullName: `${fullName}OauthSettings`,
        externalClientApplication: fullName,
        label: `${fullName} OAuth Settings`,
        callbackUrl: flags['oauth-callback-url'],
        scopes,
        isImplicitHashAlgAndTokenIdEnforced: true,
      };

      const oauthResult = (await connection.metadata.create('ExternalClientOauthSettings', oauthMetadata)) as SaveResult;

      if (oauthResult.success) {
        this.spinner.stop();
        this.log(`Successfully created External Client App and OAuth Settings: ${fullName}`);
        return { fullName, success: true };
      } else {
        throw new Error(`OAuth Settings Error: ${oauthResult.errors?.[0]?.message}`);
      }

    } catch (err) {
      this.spinner.stop('Error');
      const msg = err instanceof Error ? err.message : String(err);
      this.error(msg);
      return { fullName, success: false, errors: [msg] };
    }
  }
}